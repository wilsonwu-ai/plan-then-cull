#!/usr/bin/env python3
"""Regenerate src/bench_asset.js from experiments/bench.py.

bench.py is served to the audience over HTTP. It cannot be embedded in a JS
template literal because it contains backslash escapes, which the literal
consumes before the browser or curl ever sees them -- the same trap that
already shipped a broken page once on a previous project. Base64 sidesteps it.

Run this after any edit to experiments/bench.py, then redeploy.
"""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "experiments/bench.py").read_bytes()
b64 = base64.b64encode(src).decode()
lines = [b64[i:i+100] for i in range(0, len(b64), 100)]
body = '",\n  "'.join(lines)
(root / "src/bench_asset.js").write_text(f'''/**
 * bench.py, base64-encoded. Generated by scripts/build_bench_asset.py -- do not edit.
 */
export const BENCH_PY_B64 = [
  "{body}"
].join("");
''')
print(f"regenerated src/bench_asset.js from bench.py ({len(src)} bytes)")
